// --- i18n Engine ---
let currentLang = localStorage.getItem('tcm-lang') || navigator.language?.slice(0,2) || 'en';
if (!translations[currentLang]) currentLang = 'en';

function t(key) {
  return translations[currentLang]?.[key] || translations.en[key] || key;
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('tcm-lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = translations[lang].dir || 'ltr';
  applyTranslations();
  // Close language modal
  const modal = document.getElementById('lang-modal');
  if (modal) modal.style.display = 'none';
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const val = t(key);
    if (el.dataset.i18nAttr) {
      el.setAttribute(el.dataset.i18nAttr, val);
    } else if (el.dataset.i18nHtml) {
      el.innerHTML = val;
    } else {
      el.textContent = val;
    }
  });
}

function showLanguageModal() {
  let modal = document.getElementById('lang-modal');
  if (!modal) {
    modal = document.createElement('div');
    modal.id = 'lang-modal';
    modal.className = 'lang-modal-overlay';
    let html = '<div class="lang-modal"><h3 data-i18n="select_language">' + t('select_language') + '</h3><div class="lang-grid">';
    for (const [code, data] of Object.entries(translations)) {
      html += `<button class="lang-btn ${code === currentLang ? 'active' : ''}" onclick="setLanguage('${code}')">${data.flag} ${data.lang}</button>`;
    }
    html += '</div><button class="lang-close" onclick="this.closest(\'.lang-modal-overlay\').style.display=\'none\'">&times;</button></div>';
    modal.innerHTML = html;
    document.body.appendChild(modal);
  } else {
    // Rebuild buttons
    const grid = modal.querySelector('.lang-grid');
    grid.innerHTML = '';
    for (const [code, data] of Object.entries(translations)) {
      grid.innerHTML += `<button class="lang-btn ${code === currentLang ? 'active' : ''}" onclick="setLanguage('${code}')">${data.flag} ${data.lang}</button>`;
    }
    modal.querySelector('h3').textContent = t('select_language');
  }
  modal.style.display = 'flex';
}

// Apply on load
document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
});
